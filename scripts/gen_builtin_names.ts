#!/usr/bin/env tsx
/**
 * Generate src/builtinNames.gen.ts: the names of numbl's builtin functions
 * and constants, for the web app's syntax highlighting and landing page.
 * Those run on the main thread, which does not import numbl-core's builtin
 * registry (see docs/developer_reference/web-app.md).
 *
 *   npx tsx scripts/gen_builtin_names.ts          # write the file
 *   npx tsx scripts/gen_builtin_names.ts --check  # exit 1 if out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
// Loading the interpreter registers every builtin name.
import "../src/numbl-core/executeCode.js";
import { getAllBuiltinNames } from "../src/numbl-core/helpers/registry.js";
import { getAllConstantNames } from "../src/numbl-core/helpers/constants.js";

const OUT_FILE = join(
  resolve(import.meta.dirname, ".."),
  "src/builtinNames.gen.ts"
);

/** `const name = "value";`, wrapped the way Prettier does past 80 columns. */
function stringConst(name: string, value: string): string {
  const oneLine = `const ${name} = ${JSON.stringify(value)};`;
  return oneLine.length <= 80
    ? oneLine
    : `const ${name} =\n  ${JSON.stringify(value)};`;
}

export function generateBuiltinNames(): string {
  const functions = [...new Set(getAllBuiltinNames())]
    .filter(n => !n.startsWith("__"))
    .sort();
  const constants = [...new Set(getAllConstantNames())].sort();
  return [
    "// Auto-generated by scripts/gen_builtin_names.ts; do not edit manually.",
    "",
    stringConst("FUNCTIONS", functions.join(" ")),
    "",
    stringConst("CONSTANTS", constants.join(" ")),
    "",
    'export const BUILTIN_FUNCTION_NAMES: readonly string[] = FUNCTIONS.split(" ");',
    "",
    'export const BUILTIN_CONSTANT_NAMES: readonly string[] = CONSTANTS.split(" ");',
    "",
  ].join("\n");
}

function readExisting(): string | null {
  try {
    return readFileSync(OUT_FILE, "utf-8");
  } catch {
    return null;
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const content = generateBuiltinNames();
  const upToDate = readExisting() === content;
  if (process.argv.includes("--check")) {
    if (!upToDate) {
      console.error(
        "src/builtinNames.gen.ts is out of date. Run: npx tsx scripts/gen_builtin_names.ts"
      );
      process.exit(1);
    }
    console.log("builtinNames.gen.ts is up to date.");
  } else if (upToDate) {
    console.log("builtinNames.gen.ts is up to date.");
  } else {
    writeFileSync(OUT_FILE, content);
    console.log("builtinNames.gen.ts written.");
  }
}
