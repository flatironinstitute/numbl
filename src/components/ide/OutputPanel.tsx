import {
  Box,
  Tab,
  Tabs,
  ToggleButton,
  ToggleButtonGroup,
  Typography,
} from "@mui/material";
import { useMemo, useState } from "react";
import { Light as SyntaxHighlighter } from "react-syntax-highlighter";
import js from "react-syntax-highlighter/dist/esm/languages/hljs/javascript";
import c from "react-syntax-highlighter/dist/esm/languages/hljs/c";
import { githubGist } from "react-syntax-highlighter/dist/esm/styles/hljs";
import type { WorkspaceRep } from "../../numblWorkerProtocol";
import { TreeViewer } from "../TreeViewer";
import { panelTabsSx } from "./panelStyles";

SyntaxHighlighter.registerLanguage("javascript", js);
SyntaxHighlighter.registerLanguage("c", c);

/** JavaScript generated by the JIT for the last run. */
export function GeneratedJsView({ code }: { code: string }) {
  return (
    <Box sx={{ height: "100%", overflow: "auto" }}>
      <SyntaxHighlighter
        language="javascript"
        style={githubGist}
        customStyle={{ margin: 0, fontSize: 12 }}
      >
        {code}
      </SyntaxHighlighter>
    </Box>
  );
}

/** AST of the last run's files (one tree per file when there are several). */
export function AstView({ rep }: { rep: WorkspaceRep | null }) {
  const astData = useMemo(() => {
    if (!rep) return null;
    const files = [rep.mainFile, ...rep.workspaceFiles];
    if (files.length === 1) return files[0].ast;
    const obj: Record<string, unknown> = {};
    for (const f of files) obj[f.name] = f.ast;
    return obj;
  }, [rep]);
  return (
    <TreeViewer
      data={astData}
      label="ast"
      fileSources={rep?.fileSources ?? null}
    />
  );
}

const subTabSx = { py: 0, px: 1, fontSize: "0.75rem", textTransform: "none" };

/** Desktop output panel: console output plus the Internals views. */
export function OutputPanel({
  output,
  generatedJS,
  workspaceRep,
  dispatchUnknownCounts,
}: {
  output: string;
  generatedJS: string;
  workspaceRep: WorkspaceRep | null;
  dispatchUnknownCounts: Record<string, number> | null;
}) {
  const [tab, setTab] = useState(0);
  const [internalsTab, setInternalsTab] = useState<"js" | "ast" | "dispatch">(
    "js"
  );
  return (
    <Box sx={{ height: "100%", display: "flex", flexDirection: "column" }}>
      <Tabs value={tab} onChange={(_, v) => setTab(v)} sx={panelTabsSx}>
        <Tab label="Output" />
        <Tab label="Internals" />
      </Tabs>
      <Box sx={{ flexGrow: 1, overflow: "hidden" }}>
        {tab === 0 && (
          <Box sx={{ height: "100%", overflow: "auto", p: 1.5 }}>
            {output ? (
              <pre
                style={{
                  margin: 0,
                  fontFamily: 'Menlo, Monaco, "Courier New", monospace',
                  fontSize: "13px",
                  lineHeight: 1.5,
                  whiteSpace: "pre-wrap",
                }}
              >
                {output}
              </pre>
            ) : (
              <Typography
                variant="body2"
                color="text.disabled"
                sx={{ fontStyle: "italic", mt: 2, textAlign: "center" }}
              >
                Run a script to see output here
              </Typography>
            )}
          </Box>
        )}
        {tab === 1 && (
          <Box
            sx={{ height: "100%", display: "flex", flexDirection: "column" }}
          >
            <Box sx={{ display: "flex", alignItems: "center", px: 1, py: 0.5 }}>
              <ToggleButtonGroup
                value={internalsTab}
                exclusive
                onChange={(_, v) => {
                  if (v) setInternalsTab(v);
                }}
                size="small"
              >
                <ToggleButton value="js" sx={subTabSx}>
                  JavaScript
                </ToggleButton>
                <ToggleButton value="ast" sx={subTabSx}>
                  AST
                </ToggleButton>
                <ToggleButton value="dispatch" sx={subTabSx}>
                  Dispatch
                </ToggleButton>
              </ToggleButtonGroup>
            </Box>
            <Box sx={{ flexGrow: 1, overflow: "hidden" }}>
              {internalsTab === "js" && <GeneratedJsView code={generatedJS} />}
              {internalsTab === "ast" && <AstView rep={workspaceRep} />}
              {internalsTab === "dispatch" && (
                <Box sx={{ height: "100%", overflow: "auto", p: 1 }}>
                  {dispatchUnknownCounts &&
                  Object.keys(dispatchUnknownCounts).length > 0 ? (
                    <pre
                      style={{
                        margin: 0,
                        fontFamily: "monospace",
                        fontSize: "13px",
                        whiteSpace: "pre-wrap",
                      }}
                    >
                      {Object.entries(dispatchUnknownCounts)
                        .sort(([, a], [, b]) => b - a)
                        .map(([name, count]) => `${name}: ${count}`)
                        .join("\n")}
                    </pre>
                  ) : (
                    <Typography variant="body2" color="text.secondary">
                      No dispatchUnknown calls
                    </Typography>
                  )}
                </Box>
              )}
            </Box>
          </Box>
        )}
      </Box>
    </Box>
  );
}
